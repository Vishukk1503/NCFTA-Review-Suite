    ('EVENT_UUID', 'VARCHAR', 'YES', 36),
    ('OBJECT_UUID', 'VARCHAR', 'YES', 36),
    ('ATTRIBUTE_UUID', 'VARCHAR', 'YES', 36),
    ('SOURCE_EVENT_ID', 'VARCHAR', 'YES', NULL),
    ('SOURCE_OBJECT_ID', 'VARCHAR', 'YES', NULL),
    ('SOURCE_ATTRIBUTE_ID', 'VARCHAR', 'YES', NULL),
    ('SOURCE_REVIEW_ID', 'VARCHAR', 'NO', NULL),
    ('EVENT_SHARING_GROUP_ID', 'VARCHAR', 'YES', NULL),
    ('ATTRIBUTE_SHARING_GROUP_ID', 'VARCHAR', 'YES', NULL),
    ('ATTRIBUTE_DISTRIBUTION', 'VARCHAR', 'YES', NULL),
    ('SOURCE_TYPE', 'VARCHAR', 'YES', NULL),
    ('SOURCE_CATEGORY', 'VARCHAR', 'YES', NULL),
    ('SOURCE_ATTRIBUTE_SHA256', 'VARCHAR', 'NO', 64),
    ('MODEL_SHA256', 'VARCHAR', 'NO', 64),
    ('CATALOG_SHA256', 'VARCHAR', 'NO', 64),
    ('PREDICTION_IDENTITY', 'VARCHAR', 'NO', 64),
    ('TRANSFORM_VERSION', 'VARCHAR', 'NO', NULL),
    ('OUTCOME_STATUS', 'VARCHAR', 'NO', NULL),
    ('SOURCE_ATTRIBUTE_DELETED', 'BOOLEAN', 'YES', NULL),
    ('SOURCE_OBJECT_DELETED', 'BOOLEAN', 'YES', NULL),
    ('IS_DELETED', 'BOOLEAN', 'NO', NULL),
    ('REVIEW_STATUS', 'VARCHAR', 'NO', NULL),
    ('WARNINGS', 'ARRAY', 'NO', NULL),
    ('APP_ROW_ID', 'VARCHAR', 'NO', 36),
    ('APP_MAPPING_VERSION', 'VARCHAR', 'NO', NULL),
    ('FIELD_PROVENANCE', 'VARIANT', 'NO', NULL),
    ('PUBLISHED_BY_LOAD_RUN_ID', 'VARCHAR', 'NO', 36),
    ('PUBLISHED_AT', 'TIMESTAMP_TZ', 'NO', NULL),
    ('ADDRESS', 'ARRAY', 'YES', NULL),
    ('REPORTED_AMOUNT', 'ARRAY', 'YES', NULL),
    ('BANK_NAME', 'ARRAY', 'YES', NULL),
    ('BANK_ADDRESS', 'ARRAY', 'YES', NULL),
    ('CRIME_DATETIME', 'ARRAY', 'YES', NULL),
    ('SUBMITTED_BY', 'ARRAY', 'YES', NULL),
    ('SWIFT_CODE', 'ARRAY', 'YES', NULL),
    ('COMMENTS', 'ARRAY', 'YES', NULL),
    ('BANK_ACCOUNT_NUMBER', 'ARRAY', 'YES', NULL),
    ('ROUTING_NUMBER', 'ARRAY', 'YES', NULL),
    ('REPORTED_ACTOR_NAME', 'ARRAY', 'YES', NULL),
    ('PHONE_NUMBER', 'ARRAY', 'YES', NULL),
    ('SOURCE_IP', 'ARRAY', 'YES', NULL),
    ('EMAIL_ADDRESS', 'ARRAY', 'YES', NULL),
    ('DATE_OF_BIRTH', 'ARRAY', 'YES', NULL),
    ('URL', 'ARRAY', 'YES', NULL),
    ('MERCHANT_CATEGORY', 'ARRAY', 'YES', NULL),
