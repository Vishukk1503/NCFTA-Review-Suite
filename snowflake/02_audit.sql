-- Replaces the earlier three-table proposal. Prepared locally, not deployed.
-- Run under an authorized role in the intended Snowflake account.
-- Existing data is preserved; missing metadata columns are added below.
-- Existing column types are not changed; inspect the definition afterward.
-- Run provisioning separately from data-load transactions.

USE DATABASE COMPLIANCE_SCREENING_SANDBOX;

-- One row per run/step/file/attempt; FILE_NAME is NULL for a batch-wide step.
-- STEP_NAME = 'RUN' identifies the single overall summary row per invocation.
-- IDs, statuses and logical uniqueness must be validated by the future loader.
-- Unknown/not-applicable counts remain NULL; timestamps carry their zone offset.
CREATE TABLE IF NOT EXISTS AUDIT_LAYER.NCFTA_LOAD_AUDIT (
  AUDIT_ID VARCHAR(36) NOT NULL,
  LOAD_RUN_ID VARCHAR(36) NOT NULL,
  SOURCE_BATCH_ID VARCHAR(36),
  SOURCE_RUN_NAME VARCHAR,
  RETRY_OF_LOAD_RUN_ID VARCHAR(36),
  STEP_NAME VARCHAR NOT NULL,
  ATTEMPT_NUMBER NUMBER(38,0) NOT NULL DEFAULT 1,
  FILE_NAME VARCHAR,
  FILE_SHA256 VARCHAR(64),
  TARGET_TABLE VARCHAR,
  STATUS VARCHAR NOT NULL,
  STARTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  FINISHED_AT TIMESTAMP_TZ,
  ROWS_EXPECTED NUMBER(38,0),
  ROWS_READ NUMBER(38,0),
  ROWS_INSERTED NUMBER(38,0),
  ROWS_UPDATED NUMBER(38,0),
  ROWS_UNCHANGED NUMBER(38,0),
  ROWS_REJECTED NUMBER(38,0),
  QUERY_ID VARCHAR,
  ERROR_CODE VARCHAR,
  SQLSTATE VARCHAR,
  ERROR_MESSAGE VARCHAR,
  SOURCE_INSTANCE_ID VARCHAR,
  SOURCE_DATE_FROM DATE,
  SOURCE_DATE_TO DATE,
  SOURCE_GROUP_IDS ARRAY,
  FILE_SIZE_BYTES NUMBER(38,0),
  REQUESTED_TARGET VARCHAR,
  LOADER_VERSION VARCHAR,
  MODEL_SHA256 VARCHAR(64),
  TRANSFORM_VERSION VARCHAR,
  APP_MAPPING_VERSION VARCHAR,
  SNOWFLAKE_ACCOUNT VARCHAR,
  SNOWFLAKE_USER VARCHAR,
  SNOWFLAKE_ROLE VARCHAR,
  SNOWFLAKE_WAREHOUSE VARCHAR,
  ELAPSED_MS NUMBER(38,0),
  LAST_HEARTBEAT_AT TIMESTAMP_TZ,
  DETAILS VARIANT
) COMMENT = 'NCFTA run, file and step audit; sanitized diagnostics only, no source values or credentials';

-- Add these nullable fields if the earlier 24-column audit table already exists.
