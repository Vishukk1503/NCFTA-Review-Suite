-- Read-only inspection; does not return audit contents or source data.
USE DATABASE COMPLIANCE_SCREENING_SANDBOX;

SELECT CURRENT_ACCOUNT() AS ACCOUNT_NAME,
       CURRENT_ROLE() AS ROLE_NAME,
       CURRENT_DATABASE() AS DATABASE_NAME;

DESCRIBE TABLE AUDIT_LAYER.NCFTA_LOAD_AUDIT;

SELECT TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME, DATA_TYPE, IS_NULLABLE,
       CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'AUDIT_LAYER'
  AND TABLE_NAME = 'NCFTA_LOAD_AUDIT'
ORDER BY ORDINAL_POSITION;
