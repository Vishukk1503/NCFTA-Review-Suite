-- Read-only inspection after layer 1 provisioning. No source rows are returned.
USE DATABASE COMPLIANCE_SCREENING_SANDBOX;

SELECT CURRENT_ACCOUNT() AS ACCOUNT_NAME,
       CURRENT_ROLE() AS ROLE_NAME,
       CURRENT_DATABASE() AS DATABASE_NAME;

DESCRIBE FILE FORMAT INTERNAL_STAGE.NCFTA_JSONL_FF;
DESCRIBE STAGE INTERNAL_STAGE.NCFTA_STAGE;
DESCRIBE TABLE RAW.NCFTA_BATCHES;
DESCRIBE TABLE RAW.NCFTA_EVENTS;
DESCRIBE TABLE RAW.NCFTA_MODEL_RESULTS;

-- Compare these actual definitions with 01_staging_and_raw.sql.
-- IF NOT EXISTS alone is not evidence that existing definitions match.
SELECT TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME, DATA_TYPE, IS_NULLABLE,
       CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'RAW'
  AND TABLE_NAME IN ('NCFTA_BATCHES', 'NCFTA_EVENTS', 'NCFTA_MODEL_RESULTS')
ORDER BY TABLE_NAME, ORDINAL_POSITION;

-- Expect PASS: SOURCE_VALUE must be nullable text. No source values are read.
SELECT CASE WHEN COUNT(*) = 1 THEN 'PASS' ELSE 'FAIL' END AS SOURCE_VALUE_CHECK
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'RAW'
  AND TABLE_NAME = 'NCFTA_MODEL_RESULTS'
  AND COLUMN_NAME = 'SOURCE_VALUE'
  AND DATA_TYPE IN ('TEXT', 'VARCHAR')
  AND IS_NULLABLE = 'YES';
